    private void registerButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_registerButtonActionPerformed
        try {
                String username = usernameValue.getText().trim();
                if (username.isEmpty())
                    throw new Exception("Vui lòng nhập tên tài khoản");

                String password = String.copyValueOf(jPasswordValue.getPassword()).trim();
                if (password.isEmpty())
                    throw new Exception("Vui lòng nhập mật khẩu");

                String nickName = nicknameValue.getText().trim();
                if (nickName.isEmpty())
                    throw new Exception("Vui lòng nhập nickname");

                String avatarToSend;

                if (selectedAvatar != null && !selectedAvatar.isEmpty()) {
                    avatarToSend = selectedAvatar;   // user_1766xxxx.jpg
                } else {
                    int index = avatarComboBox.getSelectedIndex();
                    if (index == -1) {
                        throw new Exception("Vui lòng chọn avatar");
                    }
                    avatarToSend = index + ".jpg";   // avatar mặc định
                }
                System.out.println("Register avatar = " + avatarToSend);
                Client.closeAllViews();
                Client.openView(
                    Client.View.GAME_NOTICE,
                    "Đăng kí tài khoản",
                    "Đang chờ phản hồi"
                );

                Client.socketHandle.write(
                    "register," + username + "," + password + "," + nickName + "," + avatarToSend
                );
            } catch (Exception ex) {
                JOptionPane.showMessageDialog(rootPane, ex.getMessage());
            }
    }//GEN-LAST:event_registerButtonActionPerformed

