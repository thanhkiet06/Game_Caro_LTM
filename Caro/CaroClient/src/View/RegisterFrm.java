    private void btnchooseActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnchooseActionPerformed
        // TODO add your handling code here:
        JFileChooser chooser = new JFileChooser();
        chooser.setDialogTitle("Chọn avatar");

        FileNameExtensionFilter filter =
                new FileNameExtensionFilter(
                        "Image files (*.jpg, *.png, *.jpeg)",
                        "jpg", "png", "jpeg"
                );
        chooser.setFileFilter(filter);

        if (chooser.showOpenDialog(this) == JFileChooser.APPROVE_OPTION) {
            try {
                File source = chooser.getSelectedFile();

                // ===== 1. assets/avatar =====
                File avatarDir = new File(
                        System.getProperty("user.dir"),
                        "assets/avatar"
                );
                if (!avatarDir.exists()) {
                    avatarDir.mkdirs();
                }

                // ===== 2. Lấy extension =====
                String originalName = source.getName();
                String ext = originalName.substring(
                        originalName.lastIndexOf(".")
                ).toLowerCase();

                // ===== 3. Tên file không trùng =====
                String fileName = "user_" + System.currentTimeMillis() + ext;

                File target = new File(avatarDir, fileName);

                // ===== 4. Copy =====
                Files.copy(
                        source.toPath(),
                        target.toPath(),
                        StandardCopyOption.REPLACE_EXISTING
                );

                // ===== 5. LƯU TÊN FILE (QUAN TRỌNG) =====
                selectedAvatar = fileName;

                System.out.println("Avatar saved: " + target.getAbsolutePath());

                // ===== 6. Preview =====
                ImageIcon icon = new ImageIcon(target.getAbsolutePath());
                Image img = icon.getImage()
                        .getScaledInstance(80, 80, Image.SCALE_SMOOTH);

                avatarComboBox.addItem(new ImageIcon(img));
                avatarComboBox.setSelectedIndex(
                        avatarComboBox.getItemCount() - 1
                );

            } catch (Exception e) {
                JOptionPane.showMessageDialog(
                        this,
                        "Không thể lưu avatar"
                );
                e.printStackTrace();
            }
        }
    }//GEN-LAST:event_btnchooseActionPerformed


